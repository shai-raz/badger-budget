/**
 * Changelog data model and its Markdown / release-notes rendering.
 *
 * The changelog JSON (`apps/api/changelog.json`) is the source of truth:
 * `{ releases: [{ version, date, summary?, items: [{ type, scope, breaking, subject, pr }] }] }`, newest release first.
 */

/**
 * @typedef {{ type: string, scope: string | null, breaking: boolean, subject: string, pr: number | null }} ChangelogItem
 * @typedef {{ version: string, date: string, summary?: string, items: ChangelogItem[] }} ChangelogRelease
 * @typedef {{ releases: ChangelogRelease[] }} Changelog
 */

const INTRO = "Generated from `apps/api/changelog.json` by the release workflow. Do not edit this file by hand.";

/** Groups in display order. Each item lands in the first group whose predicate matches. */
const GROUPS = [
    { title: "Breaking changes", matches: (/** @type {ChangelogItem} */ item) => item.breaking },
    { title: "Features", matches: (/** @type {ChangelogItem} */ item) => item.type === "feat" },
    { title: "Bug fixes", matches: (/** @type {ChangelogItem} */ item) => item.type === "fix" },
    { title: "Performance", matches: (/** @type {ChangelogItem} */ item) => item.type === "perf" },
    { title: "Other changes", matches: () => true },
];

/**
 * Returns a new changelog with the release added first.
 * @param {Changelog} changelog
 * @param {ChangelogRelease} release
 * @returns {Changelog}
 */
export function prependRelease(changelog, release) {
    if (changelog.releases.some((existing) => existing.version === release.version)) {
        throw new Error(`Release ${release.version} is already in the changelog`);
    }
    return { ...changelog, releases: [release, ...changelog.releases] };
}

/**
 * Renders the whole changelog as CHANGELOG.md.
 * @param {Changelog} changelog
 * @param {string} repo `owner/name`
 * @returns {string}
 */
export function renderChangelogMarkdown(changelog, repo) {
    const sections = changelog.releases.map((release) =>
        [
            `## [${release.version}](https://github.com/${repo}/releases/tag/v${release.version}) - ${release.date}`,
            ...releaseBlocks(release, repo),
        ].join("\n\n"),
    );
    return ["# Changelog", INTRO, ...sections].join("\n\n") + "\n";
}

/**
 * Renders one release as GitHub release notes (no version heading).
 * @param {ChangelogRelease} release
 * @param {string} repo `owner/name`
 * @returns {string}
 */
export function renderReleaseNotes(release, repo) {
    return releaseBlocks(release, repo).join("\n\n") + "\n";
}

/**
 * The summary paragraph followed by one `### Group` block per non-empty group.
 * @param {ChangelogRelease} release
 * @param {string} repo
 * @returns {string[]}
 */
function releaseBlocks(release, repo) {
    const blocks = release.summary ? [release.summary] : [];
    for (const group of GROUPS) {
        const items = release.items.filter((item) => group.matches(item) && !isEarlierGroup(item, group.title));
        if (items.length === 0) {
            continue;
        }
        const bullets = items.map((item) => renderBullet(item, repo));
        blocks.push([`### ${group.title}`, bullets.join("\n")].join("\n\n"));
    }
    return blocks;
}

/**
 * True when an earlier group already claimed the item, so each item renders exactly once.
 * @param {ChangelogItem} item
 * @param {string} title
 * @returns {boolean}
 */
function isEarlierGroup(item, title) {
    const index = GROUPS.findIndex((group) => group.title === title);
    return GROUPS.slice(0, index).some((group) => group.matches(item));
}

/**
 * @param {ChangelogItem} item
 * @param {string} repo
 * @returns {string}
 */
function renderBullet(item, repo) {
    const scope = item.scope ? `**${escapeMarkdown(item.scope)}:** ` : "";
    const pr = typeof item.pr === "number" ? ` ([#${item.pr}](https://github.com/${repo}/pull/${item.pr}))` : "";
    return `- ${scope}${escapeMarkdown(item.subject)}${pr}`;
}

/**
 * Backslash-escapes the Markdown a commit subject can carry, so GitHub renders it as typed. Underscores are escaped
 * only at word edges, where they would start or end emphasis; `snake_case` stays readable. The word-edge test is
 * Unicode-aware, so `é_x_é` is not escaped, because CommonMark does not treat an intraword underscore as emphasis.
 * CHANGELOG.md is excluded from Prettier, so these escapes only need to render correctly, not survive a reformat.
 * @param {string} text
 * @returns {string}
 */
function escapeMarkdown(text) {
    return text
        .replace(/[\\`*[\]<>&~#|]/g, "\\$&")
        .replace(/(?<![\p{L}\p{N}])_|_(?![\p{L}\p{N}])/gu, "\\_")
        .replace(/^[+-](?=\s|$)/, "\\$&")
        .replace(/^(\d+)([.)])(?=\s|$)/, "$1\\$2");
}
