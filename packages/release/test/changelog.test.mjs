import { test } from "node:test";
import assert from "node:assert/strict";
import { prependRelease, renderChangelogMarkdown, renderReleaseNotes } from "../src/changelog.mjs";

const REPO = "owner/badger";

const newest = {
    version: "0.2.0",
    date: "2026-10-22",
    summary: "Adds the version banner.",
    items: [
        { type: "feat", scope: "web", breaking: false, subject: "show running version", pr: 31 },
        { type: "fix", scope: null, breaking: false, subject: "fix login redirect", pr: null },
        { type: "refactor", scope: "api", breaking: false, subject: "tidy modules", pr: 30 },
        { type: "feat", scope: "api", breaking: true, subject: "drop legacy endpoint", pr: 29 },
    ],
};

const oldest = {
    version: "0.1.0",
    date: "2026-10-01",
    items: [{ type: "perf", scope: null, breaking: false, subject: "speed up charts", pr: 12 }],
};

const changelog = { releases: [newest, oldest] };

test("prependRelease adds the release first without mutating the input", () => {
    const next = { version: "0.3.0", date: "2026-10-23", items: [] };
    const result = prependRelease(changelog, next);
    assert.deepEqual(
        result.releases.map((release) => release.version),
        ["0.3.0", "0.2.0", "0.1.0"],
    );
    assert.deepEqual(
        changelog.releases.map((release) => release.version),
        ["0.2.0", "0.1.0"],
    );
});

test("prependRelease throws when the version already exists", () => {
    assert.throws(
        () => prependRelease(changelog, { version: "0.1.0", date: "2026-10-23", items: [] }),
        /0\.1\.0 is already in the changelog/,
    );
});

test("renderChangelogMarkdown renders groups, bullets and links exactly", () => {
    const expected = [
        "# Changelog",
        "Generated from `apps/api/changelog.json` by the release workflow. Do not edit this file by hand.",
        [
            "## [0.2.0](https://github.com/owner/badger/releases/tag/v0.2.0) - 2026-10-22",
            "Adds the version banner.",
            "### Breaking changes\n\n- **api:** drop legacy endpoint ([#29](https://github.com/owner/badger/pull/29))",
            "### Features\n\n- **web:** show running version ([#31](https://github.com/owner/badger/pull/31))",
            "### Bug fixes\n\n- fix login redirect",
            "### Other changes\n\n- **api:** tidy modules ([#30](https://github.com/owner/badger/pull/30))",
        ].join("\n\n"),
        [
            "## [0.1.0](https://github.com/owner/badger/releases/tag/v0.1.0) - 2026-10-01",
            "### Performance\n\n- speed up charts ([#12](https://github.com/owner/badger/pull/12))",
        ].join("\n\n"),
    ].join("\n\n");

    assert.equal(renderChangelogMarkdown(changelog, REPO), expected + "\n");
});

test("renderReleaseNotes renders one release without the version heading", () => {
    const expected = [
        "Adds the version banner.",
        "### Breaking changes\n\n- **api:** drop legacy endpoint ([#29](https://github.com/owner/badger/pull/29))",
        "### Features\n\n- **web:** show running version ([#31](https://github.com/owner/badger/pull/31))",
        "### Bug fixes\n\n- fix login redirect",
        "### Other changes\n\n- **api:** tidy modules ([#30](https://github.com/owner/badger/pull/30))",
    ].join("\n\n");

    assert.equal(renderReleaseNotes(newest, REPO), expected + "\n");
    assert.equal(
        renderReleaseNotes(oldest, REPO),
        "### Performance\n\n- speed up charts ([#12](https://github.com/owner/badger/pull/12))\n",
    );
});
