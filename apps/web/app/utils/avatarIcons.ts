export type AvatarSize = "xs" | "sm" | "md" | "lg";

/** Box classes and glyph size (px) for each `EntityAvatar` size. */
export const AVATAR_SIZES: Record<AvatarSize, { box: string; icon: number }> = {
    xs: { box: "h-5 w-5", icon: 12 },
    sm: { box: "h-7 w-7", icon: 16 },
    md: { box: "h-9 w-9 md:h-10 md:w-10", icon: 18 },
    lg: { box: "h-14 w-14", icon: 28 },
};

/**
 * Resolve a stored icon name to its Lucide component. Unknown names, `null`, and
 * legacy PrimeIcons/Font Awesome names (e.g. "tshirt") return the fallback's component.
 */
export function resolveAvatarIcon(name: string | null | undefined, fallback: AvatarIconName): Component {
    return AVATAR_ICONS[isAvatarIconName(name) ? name : fallback];
}

const ACCOUNT_FALLBACK_ICONS: Record<AccountType, AvatarIconName> = {
    bank: "landmark",
    credit_card: "credit-card",
    cash: "wallet",
    savings: "piggy-bank",
    unknown: "landmark",
};

/**
 * Default icon for an account with no stored icon, keyed by account type.
 * Cash accounts get a wallet, savings a piggy bank, credit cards a card, and bank or unknown accounts a bank.
 */
export function accountFallbackIcon(type: AccountType): AvatarIconName {
    return ACCOUNT_FALLBACK_ICONS[type];
}
